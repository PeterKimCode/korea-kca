create table if not exists public.slides (
  id uuid primary key default gen_random_uuid(),
  image_url text not null,
  alt_text text not null,
  sort_order integer not null default 0,
  published boolean not null default true,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.content_history (
  id bigint generated always as identity primary key,
  entity_type text not null check (entity_type in ('courses', 'notices', 'slides')),
  entity_id uuid not null,
  action text not null check (action in ('insert', 'update', 'delete', 'restore')),
  before_data jsonb,
  after_data jsonb,
  actor_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists courses_public_idx on public.courses (published, deleted_at, group_key, sort_order);
create index if not exists notices_public_idx on public.notices (published, deleted_at, published_at desc);
create index if not exists slides_public_idx on public.slides (published, deleted_at, sort_order);
create index if not exists history_recent_idx on public.content_history (created_at desc);

create or replace function public.is_gtcc_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users where user_id = auth.uid()
  );
$$;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.audit_content_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  action_name text;
begin
  if tg_op = 'INSERT' then
    action_name := 'insert';
    insert into public.content_history(entity_type, entity_id, action, before_data, after_data, actor_id)
    values (tg_table_name, new.id, action_name, null, to_jsonb(new), auth.uid());
    return new;
  end if;

  if old.deleted_at is null and new.deleted_at is not null then
    action_name := 'delete';
  elsif old.deleted_at is not null and new.deleted_at is null then
    action_name := 'restore';
  else
    action_name := 'update';
  end if;

  insert into public.content_history(entity_type, entity_id, action, before_data, after_data, actor_id)
  values (tg_table_name, new.id, action_name, to_jsonb(old), to_jsonb(new), auth.uid());
  return new;
end;
$$;

