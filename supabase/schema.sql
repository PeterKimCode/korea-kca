create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '관리자',
  created_at timestamptz not null default now()
);

create table if not exists public.courses (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null,
  category text not null,
  group_key text not null check (group_key in ('popular', 'new', 'middle', 'career', 'pass')),
  image_url text not null,
  tags text[] not null default '{}',
  summary text not null default '',
  curriculum text[] not null default '{}',
  duration text not null default '4주',
  exam_type text not null default '온라인시험',
  benefit_label text not null default '장학지원',
  sort_order integer not null default 0,
  published boolean not null default true,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notices (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity unique,
  title text not null,
  body text not null default '',
  image_url text,
  link_url text,
  link_label text,
  author text not null default 'GTCC대학교평생교육원',
  published_at date not null default current_date,
  published boolean not null default true,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

